#include "ft_printf.h"

int	ft_put_int(int x)
{
	char	*c;
	int		i;

	i = 0;
	c = ft_itoa(x);
	while (c[i] != '\0')
	{
		write (1, &c[i], 1);
		i++;
	}
	free (c);
	return (i);
}
