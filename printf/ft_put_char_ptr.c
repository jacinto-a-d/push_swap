#include "ft_printf.h"

int	ft_put_char_ptr(char *x)
{
	int		i;

	i = 0;
	if (!x)
	{
		write (1, "(null)", 6);
		return (6);
	}
	while (x[i])
	{
		write (1, &x[i], 1);
		i++;
	}
	return (i);
}
